-- 1. Tabla de metadata de documentos -------------------------

create table if not exists public.documentos (
  id                 bigint generated by default as identity primary key,
  -- Dueño de la fila. El DEFAULT hace que la app no tenga que mandarlo.
  user_id            uuid        not null default auth.uid(),
  propiedad_id       bigint      references public.propiedades (id) on delete set null,
  contrato_id        bigint      references public.contratos (id) on delete set null,
  inquilino_id       bigint      references public.inquilinos (id) on delete set null,
  categoria          text        not null default 'OTRO',
  nombre             text        not null,
  descripcion        text,
  ruta               text        not null unique,
  mime_type          text,
  tamanio            bigint,
  fecha_documento    date,
  fecha_alta         timestamptz not null default now(),
  fecha_modificacion timestamptz not null default now(),
  eliminado          smallint    not null default 0,

  -- Un documento cuelga de una propiedad, de un contrato o de un
  -- inquilino: exactamente uno de los tres.
  constraint documentos_un_solo_vinculo check (
    (propiedad_id is not null)::int +
    (contrato_id is not null)::int +
    (inquilino_id is not null)::int = 1
  )
);

create index if not exists documentos_user_id_idx
  on public.documentos (user_id);

create index if not exists documentos_propiedad_idx
  on public.documentos (propiedad_id)
  where eliminado = 0;

create index if not exists documentos_contrato_idx
  on public.documentos (contrato_id)
  where eliminado = 0;

create index if not exists documentos_inquilino_idx
  on public.documentos (inquilino_id)
  where eliminado = 0;

-- 2. Seguridad a nivel de fila ------------------------------
-- Cada usuario ve y toca únicamente sus propias filas.

alter table public.documentos enable row level security;

drop policy if exists documentos_acceso_autenticado on public.documentos;

create policy documentos_por_usuario
  on public.documentos
  for all
  to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- 3. Bucket privado para los archivos -----------------------

insert into storage.buckets (id, name, public)
values ('documentos', 'documentos', false)
on conflict (id) do nothing;

-- 4. Políticas sobre los objetos del bucket -----------------
-- `owner` lo completa Supabase Storage con quien sube el archivo.
-- Se compara como texto en ambos lados porque `owner` fue text en
-- versiones viejas de Supabase y uuid en las nuevas.
-- La condición `or owner is null` es una red de seguridad: si Storage
-- no llegara a completar `owner` antes de evaluar la política, sin ella
-- las subidas fallarían. Si querés el máximo rigor, borrala de las
-- cuatro políticas una vez que compruebes que las subidas funcionan.

drop policy if exists documentos_bucket_leer on storage.objects;
drop policy if exists documentos_bucket_subir on storage.objects;
drop policy if exists documentos_bucket_actualizar on storage.objects;
drop policy if exists documentos_bucket_borrar on storage.objects;

create policy documentos_bucket_leer
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'documentos'
    and (owner::text = auth.uid()::text or owner is null)
  );

create policy documentos_bucket_subir
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'documentos'
    and (owner::text = auth.uid()::text or owner is null)
  );

create policy documentos_bucket_actualizar
  on storage.objects
  for update
  to authenticated
  using (
    bucket_id = 'documentos'
    and (owner::text = auth.uid()::text or owner is null)
  );

create policy documentos_bucket_borrar
  on storage.objects
  for delete
  to authenticated
  using (
    bucket_id = 'documentos'
    and (owner::text = auth.uid()::text or owner is null)
  );
