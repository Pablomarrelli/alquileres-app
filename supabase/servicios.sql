-- 1. Medidores -----------------------------------------------
-- Cada inquilino tiene su propio medidor. El medidor pertenece a
-- la propiedad; inquilino_id es la asignación vigente y sirve para
-- precargar el reparto. La liquidación guarda el inquilino real,
-- así que si cambia el inquilino el historial no se rompe.

create table if not exists public.medidores (
  id                 bigint generated by default as identity primary key,
  -- Dueño de la fila. El DEFAULT hace que la app no tenga que mandarlo.
  user_id            uuid        not null default auth.uid(),
  propiedad_id       bigint      not null references public.propiedades (id) on delete cascade,
  inquilino_id       bigint      references public.inquilinos (id) on delete set null,
  tipo_servicio      text        not null default 'LUZ',
  etiqueta           text,
  numero             text,
  unidad             text        not null default 'kWh',
  activo             smallint    not null default 1,
  observaciones      text,
  fecha_alta         timestamptz not null default now(),
  fecha_modificacion timestamptz not null default now(),
  eliminado          smallint    not null default 0
);

create index if not exists medidores_propiedad_idx
  on public.medidores (propiedad_id)
  where eliminado = 0;

-- Un inquilino no puede tener dos medidores activos del mismo servicio.
create unique index if not exists medidores_inquilino_servicio_uidx
  on public.medidores (inquilino_id, tipo_servicio)
  where eliminado = 0 and activo = 1 and inquilino_id is not null;


-- 2. Lecturas ------------------------------------------------
-- Historial de lecturas por medidor. La clave (medidor_id, fecha)
-- permite cargar el par inicial/final de cada boleta sin duplicar.

create table if not exists public.lecturas (
  id                 bigint generated by default as identity primary key,
  user_id            uuid          not null default auth.uid(),
  medidor_id         bigint        not null references public.medidores (id) on delete cascade,
  fecha              date          not null,
  valor              numeric(12,2) not null,
  documento_id       bigint        references public.documentos (id) on delete set null,
  observaciones      text,
  fecha_alta         timestamptz   not null default now(),
  fecha_modificacion timestamptz   not null default now(),
  eliminado          smallint      not null default 0,

  constraint lecturas_una_por_dia unique (medidor_id, fecha)
);

create index if not exists lecturas_medidor_fecha_idx
  on public.lecturas (medidor_id, fecha desc)
  where eliminado = 0;


-- 3. Boletas -------------------------------------------------
-- La boleta del proveedor. cargo_fijo y consumo_facturado son
-- INFORMATIVOS: el reparto elegido usa solo importe_total, porque
-- todo se reparte en proporción al consumo medido.

create table if not exists public.boletas (
  id                 bigint generated by default as identity primary key,
  user_id            uuid          not null default auth.uid(),
  -- Propiedad "principal", OPCIONAL: una boleta del proveedor puede
  -- cubrir varias casas. El reparto se define por los contadores que
  -- elijas, no por esta columna.
  propiedad_id       bigint        references public.propiedades (id) on delete set null,
  tipo_servicio      text          not null default 'LUZ',
  criterio           text          not null default 'CONSUMO',
  periodo            text          not null,
  periodo_desde      date,
  periodo_hasta      date,
  numero_comprobante text,
  fecha_emision      date,
  fecha_vencimiento  date,
  importe_total      numeric(12,2) not null,
  cargo_fijo         numeric(12,2),
  consumo_facturado  numeric(12,2),
  -- Estado de pago HACIA LA PROVEEDORA (vos → la empresa). Es distinto
  -- del cobro al inquilino, que vive en liquidaciones.estado.
  estado             text          not null default 'PENDIENTE',
  fecha_pago         date,
  medio_pago_id      bigint        references public.medios_pago (id) on delete set null,
  documento_id       bigint        references public.documentos (id) on delete set null,
  observaciones      text,
  fecha_alta         timestamptz   not null default now(),
  fecha_modificacion timestamptz   not null default now(),
  eliminado          smallint      not null default 0,

  constraint boletas_criterio_valido
    check (criterio in ('CONSUMO', 'PARTES_IGUALES')),
  constraint boletas_estado_valido
    check (estado in ('PENDIENTE', 'PAGADA')),
  constraint boletas_periodo_valido
    check (periodo ~ '^\d{4}-\d{2}$'),
  constraint boletas_importe_positivo
    check (importe_total > 0)
);

create index if not exists boletas_propiedad_periodo_idx
  on public.boletas (propiedad_id, periodo desc)
  where eliminado = 0;

create index if not exists boletas_vencimiento_idx
  on public.boletas (fecha_vencimiento)
  where eliminado = 0;

create index if not exists boletas_por_pagar_idx
  on public.boletas (fecha_vencimiento)
  where eliminado = 0 and estado = 'PENDIENTE';


-- 4. Liquidaciones -------------------------------------------
-- Lo que le toca pagar a cada inquilino por una boleta.
-- El consumo y el importe quedan CONGELADOS: si después corregís
-- una lectura, el historial ya cobrado no cambia.

create table if not exists public.liquidaciones (
  id                 bigint generated by default as identity primary key,
  user_id            uuid          not null default auth.uid(),
  boleta_id          bigint        not null references public.boletas (id) on delete cascade,
  medidor_id         bigint        references public.medidores (id) on delete set null,
  inquilino_id       bigint        not null references public.inquilinos (id) on delete cascade,
  contrato_id        bigint        references public.contratos (id) on delete set null,
  lectura_inicial_id bigint        references public.lecturas (id) on delete set null,
  lectura_final_id   bigint        references public.lecturas (id) on delete set null,
  consumo            numeric(12,2),
  proporcion         numeric(9,6),
  importe            numeric(12,2) not null,
  estado             text          not null default 'PENDIENTE',
  fecha_pago         date,
  observaciones      text,
  fecha_alta         timestamptz   not null default now(),
  fecha_modificacion timestamptz   not null default now(),
  eliminado          smallint      not null default 0,

  constraint liquidaciones_una_por_inquilino unique (boleta_id, inquilino_id),
  constraint liquidaciones_estado_valido
    check (estado in ('PENDIENTE', 'PAGADA')),
  constraint liquidaciones_importe_positivo
    check (importe >= 0)
);

create index if not exists liquidaciones_boleta_idx
  on public.liquidaciones (boleta_id)
  where eliminado = 0;

create index if not exists liquidaciones_inquilino_idx
  on public.liquidaciones (inquilino_id)
  where eliminado = 0;

create index if not exists medidores_user_id_idx    on public.medidores (user_id);
create index if not exists lecturas_user_id_idx     on public.lecturas (user_id);
create index if not exists boletas_user_id_idx      on public.boletas (user_id);
create index if not exists liquidaciones_user_id_idx on public.liquidaciones (user_id);

-- NOTA: 'VENCIDA' no se guarda. Se calcula en la app cuando
-- estado = 'PENDIENTE' y la boleta ya pasó su fecha_vencimiento,
-- así el dato nunca queda desactualizado.


-- 5. Seguridad a nivel de fila -------------------------------
-- Cada usuario ve y toca únicamente sus propias filas.

alter table public.medidores    enable row level security;
alter table public.lecturas     enable row level security;
alter table public.boletas      enable row level security;
alter table public.liquidaciones enable row level security;

drop policy if exists medidores_acceso_autenticado on public.medidores;
drop policy if exists lecturas_acceso_autenticado on public.lecturas;
drop policy if exists boletas_acceso_autenticado on public.boletas;
drop policy if exists liquidaciones_acceso_autenticado on public.liquidaciones;

create policy medidores_por_usuario
  on public.medidores for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy lecturas_por_usuario
  on public.lecturas for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy boletas_por_usuario
  on public.boletas for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy liquidaciones_por_usuario
  on public.liquidaciones for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
